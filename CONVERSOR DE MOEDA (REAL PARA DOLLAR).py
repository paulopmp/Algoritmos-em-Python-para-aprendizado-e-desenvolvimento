# CONVERSOR DE MOEDA (REAL PARA DOLLAR)

valor_em_reais = float(input('Digite o seu valor em reais: '))

taxa_de_cambio = float (input('Digite o valor da taxa de câmbio do Dollar: '))

valor_convertido = valor_em_reais / taxa_de_cambio


print("O valor digitado em reais equivale em dollar(s) a: ", valor_convertido)
